import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { DEFAULT_APP_REGISTRY } from '../src/default-app-registry.mjs';

export async function composeInstallation({ root = fileURLToPath(new URL('../', import.meta.url)), registry = DEFAULT_APP_REGISTRY } = {}) {
  const compose = JSON.parse(await readFile(resolve(root, 'config/compose-platform.json'), 'utf8'));
  for (const app of registry.apps) {
    const recipe = app.integration.deployment?.localCompose;
    if (!recipe) continue;
    for (const [name, service] of Object.entries(recipe.services || {})) {
      if (!/^[a-z][a-z0-9-]{0,79}$/.test(name) || Object.hasOwn(compose.services, name)) throw new Error('Duplicate or invalid installation service.');
      if (service.build?.context !== './' + app.source || service.build?.dockerfile !== app.integration.deployment.native?.dockerfile) throw new Error('Native builds must use their own installed source recipe.');
      compose.services[name] = structuredClone(service);
      compose.services.praxis.depends_on[name] = { condition: 'service_healthy', required: true };
    }
    for (const [name, volume] of Object.entries(recipe.volumes || {})) {
      if (!/^[a-z][a-z0-9-]{0,79}$/.test(name) || Object.hasOwn(compose.volumes, name)) throw new Error('Duplicate or invalid installation volume.');
      compose.volumes[name] = structuredClone(volume);
    }
    compose.services.initialize.volumes.push(...structuredClone(recipe.initializeVolumes || []));
    compose.services.praxis.volumes.push(...structuredClone(recipe.webVolumes || []));
  }
  return compose;
}
export function renderDockerContext(base, registry = DEFAULT_APP_REGISTRY) {
  const patterns = new Set();
  const add = (app, path) => {
    if (typeof path !== 'string' || !path || path.startsWith('/') || /[\\\x00-\x1f\x7f?#]/.test(path) || path.split('/').some(part => !part || part === '.' || part === '..') || path.split('/').some(part => part.startsWith('.git'))) throw new Error('Invalid app build-context declaration.');
    patterns.add('!' + app.source + '/' + path);
  };
  for (const app of registry.apps) {
    for (const path of ['praxis-app.json', 'praxis-integration.mjs', 'praxis-provider.mjs', 'apps.example.json', 'package.json', 'package-lock.json', 'praxis/**', 'skills/*/SKILL.md', 'src/**/*.mjs', 'src/**/*.js', 'src/*.mjs', 'src/*.js', '**/*.md', app.iconPath]) {
      // readApps keeps the public icon URL separate from its owning source path.
      if (path && !path.startsWith('/')) add(app, path);
    }
    const web = app.integration.web;
    if (web.kind === 'static' || web.kind === 'private-documents') {
      add(app, web.directory + '/index.html');
      for (const path of web.assets || []) if (path !== '/') add(app, web.directory + '/' + path.replace(/^\//, ''));
    }
    for (const path of app.integration.deployment?.platformFiles || []) add(app, path);
  }
  return '# Generated by node scripts/generate-compose.mjs from reviewed installed app declarations.\n' + base.trimEnd() + '\n' + [...patterns].sort().join('\n') + '\n# Never ship dependency caches or Git metadata.\n**/node_modules/**\n**/.git\n**/.git/**\n';
}
export const renderCompose = compose => '# Generated by node scripts/generate-compose.mjs from installed app-owned recipes.\n' + JSON.stringify(compose, null, 2) + '\n';
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const root = fileURLToPath(new URL('../', import.meta.url));
  const contextApps = await Promise.all(DEFAULT_APP_REGISTRY.apps.map(async app => ({ ...app, iconPath: JSON.parse(await readFile(resolve(DEFAULT_APP_REGISTRY.root, app.source, 'praxis-app.json'), 'utf8')).icon })));
  const files = new Map([['compose.yaml', renderCompose(await composeInstallation({ root }))], ['.dockerignore', renderDockerContext(await readFile(resolve(root, 'config/docker-context.txt'), 'utf8'), { apps: contextApps })]]);
  for (const [name, content] of files) {
    const file = resolve(root, name);
    if (process.argv.includes('--check')) { if (await readFile(file, 'utf8') !== content) throw new Error('Regenerate the installed source artifacts.'); }
    else await writeFile(file, content);
  }
}
